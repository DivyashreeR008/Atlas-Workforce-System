"""Control-flow tests for scripts/break_glass.py (issue #437).

These tests use simulated custodians: shares are generated by ``init`` inside
a pytest tmp_path (outside the repository), and the clock is controlled so
expiry is deterministic. No real credential material is involved.
"""

import json
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "scripts"))

import break_glass  # noqa: E402

CUSTODIANS = ["custodian-alice", "custodian-bob"]
ADMINS = ["admin1@atlas.example", "admin2@atlas.example"]


@pytest.fixture
def clock(monkeypatch):
    """Deterministic clock; advance with clock.advance(hours=...)."""
    state = {"now": datetime(2026, 10, 1, 12, 0, 0, tzinfo=timezone.utc)}

    def fake_now():
        return state["now"]

    monkeypatch.setattr(break_glass, "_now", fake_now)

    class Clock:
        @staticmethod
        def advance(**kwargs):
            state["now"] = state["now"] + timedelta(**kwargs)
            return state["now"]

    return Clock


def init_vault(tmp_path, *extra):
    vault = tmp_path / "break-glass-vault"
    argv = [
        "init", "--dir", str(vault),
        "--custodian", CUSTODIANS[0],
        "--custodian", CUSTODIANS[1],
        *[arg for admin in ADMINS for arg in ("--admin", admin)],
        *extra,
    ]
    rc = break_glass.main(argv)
    assert rc == 0
    return vault


def read_shares(vault):
    return sorted((vault / "custodians").glob("*.share"))


def activate(vault, shares, *extra):
    argv = [
        "activate", "--dir", str(vault),
        "--incident", "INC-437-TEST",
        "--reason", "simulated drill",
    ]
    for share in shares:
        argv += ["--custodian-file", str(share)]
    argv += list(extra)
    return break_glass.main(argv)


def audit_events(vault):
    return [record["event"] for record in break_glass._read_audit(vault)]


def grant_files(vault):
    return sorted((vault / "grants").glob("*.json"))


def alerts(vault):
    path = vault / "alerts.jsonl"
    if not path.is_file():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]


# ── two-person control ──────────────────────────────────────────────────────

def test_init_requires_two_custodians(tmp_path, capsys):
    vault = tmp_path / "v"
    rc = break_glass.main([
        "init", "--dir", str(vault), "--custodian", "only-one",
        "--admin", ADMINS[0],
    ])
    assert rc == 1
    assert "two-person control" in capsys.readouterr().err
    assert not (vault / "metadata.json").exists()


def test_single_custodian_cannot_activate(tmp_path, clock, capsys):
    vault = init_vault(tmp_path)
    shares = read_shares(vault)
    rc = activate(vault, shares[:1])
    assert rc == 1
    assert "quorum not met" in capsys.readouterr().err
    assert grant_files(vault) == []
    assert "access_granted" not in audit_events(vault)


def test_same_custodian_twice_does_not_meet_quorum(tmp_path, clock, capsys):
    vault = init_vault(tmp_path)
    share = read_shares(vault)[0]
    rc = activate(vault, [share, share])
    assert rc == 1
    assert "more than one share" in capsys.readouterr().err
    assert grant_files(vault) == []


def test_wrong_share_is_rejected(tmp_path, clock, capsys):
    vault = init_vault(tmp_path)
    rogue = tmp_path / "rogue.share"
    rogue.write_text("00" * 32 + "\n", encoding="utf-8")
    shares = read_shares(vault)
    rc = activate(vault, [shares[0], rogue])
    assert rc == 1
    assert "does not match any registered custodian" in capsys.readouterr().err
    assert grant_files(vault) == []


def test_two_custodians_activate(tmp_path, clock, capsys):
    vault = init_vault(tmp_path)
    rc = activate(vault, read_shares(vault))
    out = capsys.readouterr().out
    assert rc == 0
    assert "Break-glass access ACTIVE" in out
    assert len(grant_files(vault)) == 1
    assert "access_granted" in audit_events(vault)
    grant = json.loads(grant_files(vault)[0].read_text(encoding="utf-8"))
    assert grant["custodians"] == ["custodian-alice", "custodian-bob"]
    assert grant["expires_at"] > grant["issued_at"]


def test_dry_run_writes_nothing(tmp_path, clock, capsys):
    vault = init_vault(tmp_path)
    rc = activate(vault, read_shares(vault), "--dry-run")
    out = capsys.readouterr().out
    assert rc == 0
    assert "DRY RUN - nothing written" in out
    assert grant_files(vault) == []
    assert "access_granted" not in audit_events(vault)
    assert alerts(vault) == []


# ── audit-first ordering ────────────────────────────────────────────────────

def test_audit_record_is_written_before_the_grant(tmp_path, clock, monkeypatch):
    vault = init_vault(tmp_path)
    order = []
    real_audit = break_glass._append_audit
    real_write = break_glass._write_json_atomic

    def audit_spy(vault_path, event, actor, details):
        order.append("audit:%s" % event)
        return real_audit(vault_path, event, actor, details)

    def write_spy(path, payload, mode=None):
        if Path(path).parent.name == "grants":
            order.append("grant-write")
        return real_write(path, payload, mode)

    monkeypatch.setattr(break_glass, "_append_audit", audit_spy)
    monkeypatch.setattr(break_glass, "_write_json_atomic", write_spy)
    assert activate(vault, read_shares(vault)) == 0
    assert order.index("audit:access_granted") < order.index("grant-write")


def test_no_grant_when_audit_write_fails(tmp_path, clock, monkeypatch, capsys):
    vault = init_vault(tmp_path)

    def broken_audit(*args, **kwargs):
        raise OSError("audit sink unavailable")

    monkeypatch.setattr(break_glass, "_append_audit", broken_audit)
    rc = activate(vault, read_shares(vault))
    assert rc == 1
    assert "no grant was created" in capsys.readouterr().err
    assert grant_files(vault) == []


# ── expiry ──────────────────────────────────────────────────────────────────

def test_grant_expires_automatically(tmp_path, clock, capsys):
    vault = init_vault(tmp_path)
    assert activate(vault, read_shares(vault), "--hours", "4") == 0
    assert break_glass.main(["check", "--dir", str(vault)]) == 0

    clock.advance(hours=4, seconds=1)
    rc = break_glass.main(["check", "--dir", str(vault)])
    assert rc == 3
    assert "NO ACTIVE BREAK-GLASS GRANT" in capsys.readouterr().out


def test_ttl_cannot_exceed_vault_max(tmp_path, clock, capsys):
    vault = init_vault(tmp_path)  # default max 4h
    rc = activate(vault, read_shares(vault), "--hours", "9")
    assert rc == 1
    assert "outside the allowed window" in capsys.readouterr().err
    assert grant_files(vault) == []


# ── alerts ──────────────────────────────────────────────────────────────────

def test_every_admin_and_the_audit_channel_are_alerted(tmp_path, clock):
    vault = init_vault(tmp_path)
    assert activate(vault, read_shares(vault)) == 0
    activation_alerts = [a for a in alerts(vault) if a["event"] == "break_glass_activated"]
    recipients = {(a["recipient"]["kind"], a["recipient"]["id"]) for a in activation_alerts}
    assert ("audit-channel", "audit-channel") in recipients
    for admin in ADMINS:
        assert ("admin", admin) in recipients
    assert all(a["delivery"] == "queued" for a in activation_alerts)


def test_revocation_alerts_and_audits(tmp_path, clock, capsys):
    vault = init_vault(tmp_path)
    assert activate(vault, read_shares(vault)) == 0
    grant_id = json.loads(grant_files(vault)[0].read_text(encoding="utf-8"))["id"]

    rc = break_glass.main(["revoke", "--dir", str(vault), "--grant-id", grant_id,
                           "--reason", "incident stable"])
    assert rc == 0
    assert "access_revoked" in audit_events(vault)
    assert any(a["event"] == "break_glass_revoked" for a in alerts(vault))
    assert break_glass.main(["check", "--dir", str(vault)]) == 3
    revoke_again = break_glass.main(["revoke", "--dir", str(vault),
                                     "--grant-id", grant_id, "--reason", "again"])
    assert revoke_again == 1


# ── audit chain and secret hygiene ──────────────────────────────────────────

def test_audit_chain_verification_detects_tampering(tmp_path, clock, capsys):
    vault = init_vault(tmp_path)
    assert activate(vault, read_shares(vault)) == 0
    assert break_glass.main(["verify-audit", "--dir", str(vault)]) == 0

    log = vault / "audit.jsonl"
    records = [json.loads(line) for line in log.read_text(encoding="utf-8").splitlines()]
    records[1]["details"]["reason"] = "backdated lie"
    log.write_text("".join(json.dumps(r, sort_keys=True) + "\n" for r in records),
                   encoding="utf-8")
    rc = break_glass.main(["verify-audit", "--dir", str(vault)])
    assert rc == 1
    assert "hash mismatch" in capsys.readouterr().err


def test_share_values_never_appear_in_output(tmp_path, clock, capsys):
    vault = init_vault(tmp_path)
    share_values = {
        path.read_text(encoding="utf-8").strip() for path in read_shares(vault)
    }
    capsys.readouterr()  # drop init output (paths only, but check both anyway)
    assert activate(vault, read_shares(vault)) == 0
    output = capsys.readouterr().out
    for value in share_values:
        assert value not in output
    metadata = (vault / "metadata.json").read_text(encoding="utf-8")
    for value in share_values:
        assert value not in metadata


def test_vault_inside_the_repository_is_refused(tmp_path, monkeypatch, capsys):
    fake_repo = tmp_path / "fake-repo"
    (fake_repo / "scripts").mkdir(parents=True)
    monkeypatch.setattr(break_glass, "REPO_ROOT", fake_repo)
    rc = break_glass.main([
        "init", "--dir", str(fake_repo / "vault"),
        "--custodian", "a", "--custodian", "b", "--admin", ADMINS[0],
    ])
    assert rc == 1
    assert "never live in the repository" in capsys.readouterr().err
